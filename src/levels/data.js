export const LEVEL_INDEX = Object.fromEntries(
  LEVELS.map((level, index) => [level.id, index]),
);

export function createLevel(levelId) {
  const source = LEVELS.find((level) => level.id === levelId) ?? LEVELS[0];
  return {
    ...source,
    platforms: source.platforms.map((platform) => ({ ...platform })),
    movingPlatforms: source.movingPlatforms.map((platform) => ({
      ...platform,
    })),
    collectibles: source.collectibles.map((item) => ({ ...item })),
    gems: source.gems.map((item) => ({ ...item })),
    checkpoints: source.checkpoints.map((point) => ({
      ...point,
      active: false,
    })),
    hazards: source.hazards.map((hazard) => ({ ...hazard })),
    rescue: { ...source.rescue, rescued: false },
  };
}
